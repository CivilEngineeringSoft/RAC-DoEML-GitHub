import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st

from doeml import doe as D
from doeml import models as M
from doeml import optimise as O
from doeml import ui
from doeml.data import GRADES, SPECIMENS


@st.cache_resource(show_spinner="Loading the models...")
def get_models():
    return M.load()


bundle, _ = get_models()
models = bundle["models"]

st.title("Optimal mix with a design of experiments")
st.caption("The ML models predict the 28-day compressive strength of every mix generated by the design; "
           "the optimal mix is then identified, and the effect of each factor is analysed (main effects, ANOVA).")

# ===================================================================== 1. general settings
st.header("1. Specimen, strength class and models", divider="gray")
c1, c2, c3, c4 = st.columns([1.2, 1, 1.2, 1.8])
spec = c1.selectbox("Specimen", list(SPECIMENS), index=2, format_func=lambda k: SPECIMENS[k]["label"], key="op_spec")
high = c2.radio("Expected strength", ["High (≥ 45 MPa)", "Low (< 45 MPa)"], key="op_class").startswith("High")
gsel = c3.selectbox("Strength grade", ["Automatic"] + GRADES, key="op_grade",
                    help="Grade used for the strength conversion factor. Automatic: deduced from each prediction.")
names = c4.multiselect("Models", M.MODEL_NAMES, default=M.MODEL_NAMES, key="op_models")
if not names:
    st.stop()

# ===================================================================== 2. base compositions and materials
st.header("2. Base composition(s) and aggregate properties", divider="gray")
st.caption("Quantities per m³ of concrete. Total fine / coarse aggregate = natural + recycled; the replacement "
           "ratios of the design split them into natural and recycled fractions (by mass). Add a row to "
           "compare several mix-design methods (they become a factor of the design).")
bases = st.data_editor(O.DEFAULT_BASES, num_rows="dynamic", hide_index=True, key="op_bases",
                       column_config={"Name": st.column_config.TextColumn(required=True)})
bases = bases.dropna(subset=["Name"]).drop_duplicates("Name")
if bases.empty:
    st.error("Define at least one base composition.")
    st.stop()

m = O.DEFAULT_MATERIALS
a1, a2, a3, a4, a5, a6, a7 = st.columns(7)
materials = {
    "nca_size": a1.number_input("NCA size (mm)", 0.0, 40.0, m["nca_size"], 1.0),
    "nca_abs": a2.number_input("NCA absorption (%)", 0.0, 10.0, m["nca_abs"], 0.05),
    "nca_ssd": a3.number_input("NCA SSD (kg/m³)", 1000.0, 3000.0, m["nca_ssd"], 10.0),
    "rca_size": a4.number_input("RCA size (mm)", 0.0, 40.0, m["rca_size"], 1.0),
    "rca_abs": a5.number_input("RCA absorption (%)", 0.0, 20.0, m["rca_abs"], 0.1),
    "rca_ssd": a6.number_input("RCA SSD (kg/m³)", 1000.0, 3000.0, m["rca_ssd"], 10.0),
    "rfa_abs": a7.number_input("RFA absorption (%)", 0.0, 25.0, m["rfa_abs"], 0.1),
}

# ===================================================================== 3. factors and design
st.header("3. Factors, levels and design", divider="gray")
chosen = st.multiselect("Factors", list(O.FACTORS), default=list(O.FACTORS)[:4], key="op_factors",
                        help="Values not chosen as factors are taken from the base composition "
                             "(replacement ratios: 0 %).")
factors, bad = [], False
cols = st.columns(max(1, len(chosen)))
for c, f in zip(cols, chosen):
    txt = c.text_input(f"Levels: {f}", O.FACTORS[f][1], key=f"op_lv_{f}")
    try:
        lv = ui.parse_levels(txt)
        if not lv:
            raise ValueError("no level")
        if "ratio" in f and (min(lv) < 0 or max(lv) > 100):
            raise ValueError("ratios must be between 0 and 100 %")
        factors.append(D.Factor(f, lv))
    except ValueError as e:
        c.error(str(e))
        bad = True
use_base = len(bases) > 1 and st.toggle("Use the base composition as a factor", value=True, key="op_usebase")
base_factor = D.Factor(O.BASE, list(bases["Name"]), numeric=False) if use_base else None
if bad or (not factors and not base_factor):
    st.stop()

d1, d2 = st.columns([1.3, 2])
design = d1.radio("Design of experiments", list(D.DESIGNS), key="op_design",
                  captions=list(D.DESIGNS.values()))
opts = {}
with d2:
    if design == "Taguchi orthogonal array":
        arr = st.selectbox("Orthogonal array", ["Automatic (smallest suitable)"] + list(D.orthogonal_arrays()),
                           key="op_array")
        opts["array"] = None if arr.startswith("Automatic") else arr
        st.caption("Factors with fewer levels than their column use the dummy-level technique.")
    elif design == "Latin hypercube":
        opts["n_runs"] = st.number_input("Number of mixes", 5, 2000, 50, key="op_nruns")
        opts["seed"] = st.number_input("Random seed", 0, 10_000, 0, key="op_seed")
        st.caption("Numeric factors vary continuously between their smallest and largest level.")
    elif design in ("Box-Behnken", "Central composite (face-centred)"):
        opts["center_points"] = st.number_input("Centre points", 1, 10, 1, key="op_cp")
        st.caption("Only the smallest and largest levels of each factor are used (coded −1 and +1), "
                   "plus the centre (0).")
try:
    dsg, info = O.make_design(factors, design, base_factor, **opts)
except ValueError as e:
    st.error(str(e))
    st.stop()
st.info(f"**{info}** → **{len(dsg)} mixes**")
with st.expander("Design matrix"):
    st.dataframe(dsg, height=250)

# ===================================================================== 4. objective
st.header("4. Optimisation criterion", divider="gray")
o1, o2 = st.columns([2, 1.2])
objective = o1.radio("Optimal mix", O.OBJECTIVES, key="op_obj")
decision = o2.selectbox("Strength used for the decision", ["Mean of the selected models"] + names, key="op_dec")
target, weights = 45.0, {}
if objective == O.OBJECTIVES[1]:
    target = o2.number_input("Target strength on the specimen (MPa)", 10.0, 120.0, 45.0, 1.0, key="op_target")
if objective == O.OBJECTIVES[2]:
    w1, w2, w3 = st.columns(3)
    weights = {"strength": w1.slider("Weight: strength", 0.0, 1.0, 1 / 3, 0.05, key="op_w1"),
               "cost": w2.slider("Weight: cost", 0.0, 1.0, 1 / 3, 0.05, key="op_w2"),
               "co2": w3.slider("Weight: CO₂", 0.0, 1.0, 1 / 3, 0.05, key="op_w3")}
with st.expander("Unit prices and CO₂ emission factors (Table 4 of the paper; editable)"):
    prices = st.data_editor(D.PRICES, hide_index=True, key="op_prices", disabled=["Constituent"])
    st.caption("Material phase only (no transport or production). Fly ash is not in Table 4: enter its values if used.")

if st.button("Run the design", type="primary", icon=":material/play_arrow:"):
    with st.spinner(f"Predicting {len(dsg)} mixes..."):
        res = O.evaluate(dsg, bases, materials, spec, high, models, names,
                         None if gsel == "Automatic" else gsel, prices)
    st.session_state["op_result"] = {"res": res, "dsg": dsg, "info": info, "names": names,
                                     "factors": list(dsg.columns), "design": design, "spec": spec, "high": high}

R = st.session_state.get("op_result")
if R is None:
    st.stop()

# ===================================================================== 5. results
res, fac = R["res"], R["factors"]
idx, scored, msg = O.choose_optimum(res, objective, decision if decision in R["names"] or
                                    decision.startswith("Mean") else "Mean of the selected models",
                                    target, weights)
ycol = O.response_column(decision if decision in R["names"] else "Mean of the selected models")
best = scored.loc[idx]
st.header("5. Results", divider="gray")
st.caption(f"{R['info']} · {len(res)} mixes · {SPECIMENS[R['spec']]['label']} · "
           f"{'high' if R['high'] else 'low'} expected strength")
st.success(f"**Optimal mix: run {int(best['Run'])}** ({msg}).")

k = st.columns(len(R["names"]) + 2)
for c, n in zip(k, R["names"]):
    c.metric(f"fc {n}", f"{best[f'fc {n} (MPa)']:.1f} MPa")
k[-2].metric("Cost", f"{best['Cost ($/m3)']:.1f} $/m³")
k[-1].metric("CO₂", f"{best['CO2 (kg/m3)']:.0f} kg/m³")

mix = res.attrs["mixes"][idx]
comp = pd.DataFrame({"Value": {**{f: best[f] for f in fac},
                               "Cement (kg/m3)": mix["Cement Content (kg/m3)"],
                               "Fly ash (kg/m3)": mix["Fly Ash Content (kg/m3)"],
                               "Water (kg/m3)": best["Water (kg/m3)"],
                               "W/B": mix["Water-to-binder ratio (W/B)"],
                               "Admixture (% of cement)": mix["Admixture Content (%)"],
                               "NCA (kg/m3)": best["NCA (kg/m3)"], "RCA (kg/m3)": best["RCA (kg/m3)"],
                               "Natural fine aggregate (kg/m3)": best["FNA (kg/m3)"],
                               "RFA (kg/m3)": best["RFA (kg/m3)"],
                               "Recycled aggregate (% of aggregates)": best["Recycled aggregate (%)"]}})
comp["Value"] = comp["Value"].map(lambda v: f"{v:.4g}" if isinstance(v, (int, float, np.floating)) else v)
st.dataframe(comp)
if (R["high"] and best[ycol] < 45) or (not R["high"] and best[ycol] >= 45):
    st.warning("The predicted strength of the optimal mix is not consistent with the expected strength class "
               "chosen in step 1.")

SECTIONS = [":material/table: All mixes", ":material/show_chart: Predictions",
            ":material/bar_chart: Main effects", ":material/functions: ANOVA", ":material/download: Download"]
section = st.segmented_control("Section", SECTIONS, default=SECTIONS[0], required=True, key="op_section",
                               label_visibility="collapsed")
pred_cols = [f"fc {n} (MPa)" for n in R["names"]]

if section == SECTIONS[0]:
    show = scored.drop(columns=["Score"]).sort_values(
        "Grey relational grade" if "Grey relational grade" in scored else ycol, ascending=False)
    st.dataframe(show.style.format(precision=2).apply(
        lambda r: ["background-color: #d4edda" if r.name == idx else "" for _ in r], axis=1),
        hide_index=True, height=420)

elif section == SECTIONS[1]:
    fig, ax = plt.subplots(figsize=(11, 3.8))
    for n in R["names"]:
        ax.plot(res["Run"], res[f"fc {n} (MPa)"], "-o", ms=3, lw=1.2, label=n, color=ui.MODEL_COLORS[n])
    ax.axvline(best["Run"], color="grey", ls="--", lw=1)
    ax.set_xlabel("Mix (run number)", fontweight="bold")
    ax.set_ylabel("Predicted fc (MPa)", fontweight="bold")
    ax.legend(ncol=len(R["names"]))
    ax.grid(alpha=0.3)
    fig.tight_layout()
    ui.show_fig(fig, "op_pred", "DoE_predicted_fc")

elif section == SECTIONS[2]:
    resp = st.selectbox("Response", pred_cols + ["fc mean (MPa)", "Cost ($/m3)", "CO2 (kg/m3)"],
                        index=len(pred_cols) if len(pred_cols) > 1 else 0, key="op_me_resp")
    sn = R["design"] == "Taguchi orthogonal array" and resp.startswith("fc") and \
        st.toggle("Signal-to-noise ratio (larger-the-better)", key="op_sn")
    data = res.assign(_y=D.sn_larger_better(res[resp]) if sn else res[resp])
    disc = [f for f in fac if data[f].nunique() <= 12]
    if not disc:
        st.info("Main-effect plots need factors with discrete levels (not available for a Latin hypercube).")
    else:
        eff = D.main_effects(data, disc, "_y")
        ncol = min(len(disc), 3)
        nrow = int(np.ceil(len(disc) / ncol))
        fig, axes = plt.subplots(nrow, ncol, figsize=(4.2 * ncol, 3.2 * nrow), squeeze=False, sharey=True)
        for ax, f in zip(axes.flat, disc):
            s = eff[f]
            ax.plot([str(x) for x in s.index], s.values, "-o", color="#1f4e78", lw=2)
            ax.axhline(data["_y"].mean(), color="grey", ls=":", lw=1)
            ax.set_title(f, fontsize=9, fontweight="bold")
            ax.grid(alpha=0.3)
        for ax in list(axes.flat)[len(disc):]:
            ax.set_visible(False)
        axes[0, 0].set_ylabel(("S/N of " if sn else "Mean of ") + resp, fontsize=9)
        fig.tight_layout()
        ui.show_fig(fig, "op_me", "DoE_main_effects")

elif section == SECTIONS[3]:
    resp = st.selectbox("Response", pred_cols + ["fc mean (MPa)", "Cost ($/m3)", "CO2 (kg/m3)"], key="op_an_resp")
    inter = st.toggle("Include two-factor interactions", value=True, key="op_inter")
    disc = [f for f in fac if res[f].nunique() <= 12]
    if not disc:
        st.info("ANOVA needs factors with discrete levels (not available for a Latin hypercube).")
    else:
        try:
            tab = D.anova(res, disc, resp, interactions=inter)
            st.dataframe(tab.style.format({"Sum Sq": "{:.3f}", "df": "{:.0f}", "F-value": "{:.2f}",
                                           "p-value": "{:.2e}", "Contribution (%)": "{:.2f}"}, na_rep="–"))
            st.caption("Type II sums of squares; factors treated as categorical. Interactions are included when "
                       "the number of runs allows it.")
            st.session_state["op_anova"] = tab
        except Exception as e:                                       # noqa: BLE001
            st.error(f"ANOVA not possible for this design: {e}")

else:
    sheets = {"Optimal mix": comp, "All mixes": scored.drop(columns=["Score"]),
              "Design matrix": R["dsg"], "Prices and CO2": prices}
    disc = [f for f in fac if res[f].nunique() <= 12]
    if disc:
        for n in pred_cols + ["fc mean (MPa)"]:
            try:
                sheets[f"ANOVA {n[3:].split(' (')[0]}"] = D.anova(res, disc, n)
            except Exception:                                        # noqa: BLE001
                pass
    st.download_button("Download all results (Excel)", ui.excel_bytes(sheets), "RAC_DoE_results.xlsx", ui.XLSX,
                       type="primary", icon=":material/download:", on_click="ignore")
